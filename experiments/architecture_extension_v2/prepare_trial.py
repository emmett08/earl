"""Prepare isolated source trees and verify the common A-to-B starting point."""

from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import shutil


CONTEXT = "architecture-context.json"
GUIDANCE = """# Session context

Read `architecture-context.json` if present. It contains a scoped EAL/2 source
and the engineer's MCP assessment of an earlier snapshot. Do not edit this file
or the context packet.
"""
EXCLUDED = {"__pycache__", ".pytest_cache", ".git", ".mypy_cache", ".ruff_cache"}
SIDECARS = {"AGENTS.md", CONTEXT}


def files(folder: Path):
    for item in sorted(folder.rglob("*")):
        if any(part in EXCLUDED for part in item.relative_to(folder).parts):
            continue
        if item.is_symlink():
            raise ValueError(f"Source tree contains a symlink: {item}")
        if item.is_file():
            yield item


def manifest(folder: Path) -> dict:
    hashes = {}
    for item in files(folder):
        rel = item.relative_to(folder).as_posix()
        if rel in SIDECARS:
            continue
        hashes[rel] = hashlib.sha256(item.read_bytes()).hexdigest()
    payload = json.dumps(hashes, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return {"schema": "architecture-extension-source/1", "files": hashes,
            "tree_sha256": hashlib.sha256(payload).hexdigest()}


def copy_source(source: Path, destination: Path) -> None:
    if destination.exists():
        raise FileExistsError(f"Destination already exists: {destination}")
    for _ in files(source):
        pass  # Fail closed on symlinks before creating the copy.
    shutil.copytree(source, destination,
                    ignore=lambda _dir, names: [name for name in names if name in EXCLUDED])


def verify_context(folder: Path, recorded: dict) -> None:
    if (folder / "AGENTS.md").read_text(encoding="utf-8") != GUIDANCE:
        raise ValueError("Shared AGENTS.md guidance changed during the coding session")
    packet = folder / CONTEXT
    expected = recorded.get("packet_sha256")
    if expected is None and packet.exists():
        raise ValueError("An unexpected EAL context packet appeared")
    if expected is not None and (not packet.is_file()
                                or hashlib.sha256(packet.read_bytes()).hexdigest() != expected):
        raise ValueError("The EAL context packet changed or disappeared")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    actions = parser.add_subparsers(dest="action", required=True)
    prepare = actions.add_parser("prepare")
    prepare.add_argument("--source", type=Path, required=True)
    prepare.add_argument("--destination", type=Path, required=True)
    prepare.add_argument("--packet", type=Path)
    prepare.add_argument("--expected-source", type=Path,
                         help="Previously recorded manifest for the common A snapshot")
    prepare.add_argument("--record", type=Path, required=True)
    finish = actions.add_parser("snapshot")
    finish.add_argument("--trial", type=Path, required=True)
    finish.add_argument("--record", type=Path, required=True)
    finish.add_argument("--destination", type=Path, required=True)
    finish.add_argument("--manifest", type=Path, required=True)
    args = parser.parse_args()

    if args.action == "prepare":
        source = args.source.resolve()
        baseline = manifest(source)
        if args.expected_source and baseline != json.loads(args.expected_source.read_text()):
            raise ValueError("A snapshot differs from the recorded common B start")
        copy_source(source, args.destination)
        (args.destination / "AGENTS.md").write_text(GUIDANCE, encoding="utf-8")
        packet_sha = None
        if args.packet:
            packet = json.loads(args.packet.read_text(encoding="utf-8"))
            if packet.get("schema") != "architecture-extension-agent-context/1":
                raise ValueError("Invalid EAL MCP context packet")
            packet_bytes = args.packet.read_bytes()
            (args.destination / CONTEXT).write_bytes(packet_bytes)
            packet_sha = hashlib.sha256(packet_bytes).hexdigest()
        record = {"schema": "architecture-extension-trial-preparation/1",
                  "source": baseline, "packet_sha256": packet_sha,
                  "guidance_sha256": hashlib.sha256(GUIDANCE.encode("utf-8")).hexdigest()}
        args.record.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n",
                               encoding="utf-8")
    else:
        record = json.loads(args.record.read_text(encoding="utf-8"))
        verify_context(args.trial, record)
        copy_source(args.trial, args.destination)
        for name in SIDECARS:
            (args.destination / name).unlink(missing_ok=True)
        output = manifest(args.destination)
        args.manifest.write_text(json.dumps(output, indent=2, sort_keys=True) + "\n",
                                 encoding="utf-8")


if __name__ == "__main__":
    main()
